package dev.chieppa.ease.textures.bc

/** Pixels in a block. */
internal const val BLOCK_PIXELS: Int = 16

/** Partitions in a two- or three-subset table. */
private const val PARTITIONS: Int = 64

private const val HEX = 16

/**
 * The BC7 tables from the format specification (as corrected in ARB_texture_compression_bptc): the
 * subset of each pixel for every two- and three-subset partition, the anchor pixels whose index
 * drops its top bit, and the interpolation weights for 2-, 3- and 4-bit indices.
 */
internal object Bc7Tables {
  /**
   * Every two-subset partition as 16 digits, the subset of pixels 0 to 15 in row order, partitions
   * in order.
   */
  private val TWO_SUBSETS =
    """
    0011001100110011 0001000100010001 0111011101110111 0001001100110111 0000000100010011
    0011011101111111 0001001101111111 0000000100110111 0000000000010011 0011011111111111
    0000000101111111 0000000000010111 0001011111111111 0000000011111111 0000111111111111
    0000000000001111 0000100011101111 0111000100000000 0000000010001110 0111001100010000
    0011000100000000 0000100011001110 0000000010001100 0111001100110001 0011000100010000
    0000100010001100 0110011001100110 0011011001101100 0001011111101000 0000111111110000
    0111000110001110 0011100110011100 0101010101010101 0000111100001111 0101101001011010
    0011001111001100 0011110000111100 0101010110101010 0110100101101001 0101101010100101
    0111001111001110 0001001111001000 0011001001001100 0011101111011100 0110100110010110
    0011110011000011 0110011010011001 0000011001100000 0100111001000000 0010011100100000
    0000001001110010 0000010011100100 0110110010010011 0011011011001001 0110001110011100
    0011100111000110 0110110011001001 0110001100111001 0111111010000001 0001100011100111
    0000111100110011 0011001111110000 0010001011101110 0100010001110111
    """
      .filterNot { it.isWhitespace() }

  /** Every three-subset partition, laid out as the two-subset ones are. */
  private val THREE_SUBSETS =
    """
    0011001102212222 0001001122112221 0000200122112211 0222002200110111 0000000011221122
    0011001100220022 0022002211111111 0011001122112211 0000000011112222 0000111111112222
    0000111122222222 0012001200120012 0112011201120112 0122012201220122 0011011211221222
    0011200122002220 0001001101121122 0111001120012200 0000112211221122 0022002200221111
    0111011102220222 0001000122212221 0000001101220122 0000110022102210 0122012200110000
    0012001211222222 0110122112210110 0000011012211221 0022110211020022 0110011020022222
    0011012201220011 0000200022112221 0000000211221222 0222002200120011 0011001200220222
    0120012001200120 0000111122220000 0120120120120120 0120201212010120 0011220011220011
    0011112222000011 0101010122222222 0000000021212121 0022112200221122 0022001100220011
    0220122102201221 0101222222220101 0000212121212121 0101010101012222 0222011102220111
    0002111200021112 0000211221122112 0222011101110222 0002111211120002 0110011001102222
    0000000021122112 0110011022222222 0022001100110022 0022112211220022 0000000000002112
    0002000100020001 0222122202221222 0101222222222222 0111201122012220
    """
      .filterNot { it.isWhitespace() }

  /** The anchor pixel of subset 1 in each two-subset partition, one hex digit each. */
  private const val ANCHOR_TWO_SECOND =
    "fffffffffffffffff282288f28228822ff6828ff28222ff66268ff22fffff22f"

  /** The anchor pixel of subset 1 in each three-subset partition. */
  private const val ANCHOR_THREE_SECOND =
    "33ff83ff88666533338f336a588685ff8f356a8ff3f5ffff3f55585a5a8dfc33"

  /** The anchor pixel of subset 2 in each three-subset partition. */
  private const val ANCHOR_THREE_THIRD =
    "f883ff38fffffff8f8f3f8f83f6affa8f3faa89a6f8f3668f3ffffffffff3ff8"

  private val WEIGHTS_2 = intArrayOf(0, 21, 43, 64)
  private val WEIGHTS_3 = intArrayOf(0, 9, 18, 27, 37, 46, 55, 64)
  private val WEIGHTS_4 = intArrayOf(0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64)

  /** The subset of every pixel, by subset count less one, then partition: `[count - 1][p]`. */
  val subsets: Array<Array<IntArray>> =
    arrayOf(
      arrayOf(IntArray(BLOCK_PIXELS)),
      Array(PARTITIONS) { p ->
        IntArray(BLOCK_PIXELS) { TWO_SUBSETS[p * BLOCK_PIXELS + it] - '0' }
      },
      Array(PARTITIONS) { p ->
        IntArray(BLOCK_PIXELS) { THREE_SUBSETS[p * BLOCK_PIXELS + it] - '0' }
      },
    )

  /** The anchor pixel of [subset] in [partition] of a block with [count] subsets. */
  fun anchor(count: Int, partition: Int, subset: Int): Int =
    when {
      subset == 0 -> 0
      count == 2 -> ANCHOR_TWO_SECOND[partition].digitToInt(HEX)
      subset == 1 -> ANCHOR_THREE_SECOND[partition].digitToInt(HEX)
      else -> ANCHOR_THREE_THIRD[partition].digitToInt(HEX)
    }

  /** The interpolation weights, out of 64, of indices of [bits] bits. */
  fun weights(bits: Int): IntArray =
    when (bits) {
      2 -> WEIGHTS_2
      3 -> WEIGHTS_3
      else -> WEIGHTS_4
    }
}
